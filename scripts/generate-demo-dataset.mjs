import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { createClient } from "@supabase/supabase-js"
import { assertTargetShape, createDemoDataset } from "./demo-dataset-lib.mjs"

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")

function argument(name) {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : undefined
}

async function fetchAll(queryPage) {
  const pageSize = 1_000
  const rows = []
  for (let from = 0; ; from += pageSize) {
    const { data, error } = await queryPage(from, from + pageSize - 1)
    if (error) throw new Error(error.message)
    rows.push(...(data ?? []))
    if (!data || data.length < pageSize) return rows
  }
}

async function readSource() {
  const inputPath = argument("--input")
  if (inputPath) {
    const parsed = JSON.parse(await readFile(resolve(projectRoot, inputPath), "utf8"))
    if (!Array.isArray(parsed.products) || !Array.isArray(parsed.priceSnapshots)) {
      throw new Error("--input must contain { products, priceSnapshots }")
    }
    return parsed
  }

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY
  if (!url || !key) {
    throw new Error(
      "Set NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY, or pass --input export.json"
    )
  }
  const supabase = createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  })
  const products = await fetchAll((from, to) =>
    supabase
      .from("products")
      .select("id,name,set_id,set_name,tcgplayer_id,variant_id,current_price,last_synced_at")
      .order("name")
      .range(from, to)
  )
  const priceSnapshots = await fetchAll((from, to) =>
    supabase
      .from("price_snapshots")
      .select("product_id,price,snapshot_date")
      .order("product_id")
      .order("snapshot_date")
      .range(from, to)
  )
  return { products, priceSnapshots }
}

function dollars(value) {
  return `$${value.toFixed(2)}`
}

const source = await readSource()
const { dataset, stats } = createDemoDataset(source.products, source.priceSnapshots)
assertTargetShape(stats)

const outputPath = resolve(
  projectRoot,
  argument("--output") ?? "src/lib/demo/dataset.ts"
)
const sourceText = `// Generated by scripts/generate-demo-dataset.mjs. Do not edit by hand.\nimport type { DemoDataset } from "./contract"\n\nexport const demoDataset = ${JSON.stringify(dataset, null, 2)} satisfies DemoDataset\n\nexport default demoDataset\n`
await writeFile(outputPath, sourceText)

console.log(`Wrote ${outputPath}`)
console.log(`As of: ${dataset.asOf}`)
console.log(
  `Catalog: ${stats.catalogCount} products; ${stats.pricedProductCount} priced; ${stats.snapshotCount} snapshots`
)
console.log(
  `Portfolio: ${stats.positionCount} positions / ${stats.unitCount} units / ${stats.setCount} sets`
)
console.log(
  `Value ${dollars(stats.totalValue)} | basis ${dollars(stats.costBasis)} | unrealized ${dollars(stats.unrealizedPnl)} (${(stats.unrealizedPnlPct * 100).toFixed(2)}%)`
)
console.log(
  `Realized ${dollars(stats.realizedPnl)} across ${stats.sellCount} partial sells`
)
console.log(
  `Mix: ${stats.winners} winners / ${stats.losers} losers; ${stats.distinctBuyDates} buy dates; 1M ${(stats.monthChangeMin * 100).toFixed(1)}%..+${(stats.monthChangeMax * 100).toFixed(1)}%`
)
